/* global console */
// Copies the prototype's line icons and wordmark into the app, so both share one set of drawings.
// The prototype's flat category art (its ART block) is not copied: the app uses the 3D images in
// assets/categories instead.
// Run after changing docs/prototypes/src/c3-art.js:  node scripts/sync-prototype-art.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, '../../../docs/prototypes/src/c3-art.js'), 'utf8');

function block(name) {
  const start = src.indexOf(`const ${name} = `);
  if (start < 0) throw new Error(`${name} not found`);
  let i = src.indexOf('{', start);
  let depth = 0;
  for (let j = i; j < src.length; j++) {
    if (src[j] === '{') depth++;
    else if (src[j] === '}' && --depth === 0) return new Function(`return (${src.slice(i, j + 1)})`)();
  }
  throw new Error(`${name} not closed`);
}
function template(name) {
  const m = src.match(new RegExp(`const ${name} = \`([\\s\\S]*?)\`;`));
  if (!m) throw new Error(`${name} not found`);
  return m[1];
}

const icons = block('ICONS');
const wordmark = template('WORDMARK')
  .replace(' role="img" aria-label="Jiffo"', '')
  .replace('class="acc"', 'fill="{brand}"');

const out = `// Generated by scripts/sync-prototype-art.mjs from docs/prototypes/src/c3-art.js. Do not edit.
export const ICONS: Record<string, string> = ${JSON.stringify(icons, null, 2)};

/** The wordmark: letters in currentColor, the speed ball in {brand}. */
export const WORDMARK = ${JSON.stringify(wordmark)};
`;
writeFileSync(join(here, '../src/ui/art.generated.ts'), out);
console.log(`icons ${Object.keys(icons).length}`);
